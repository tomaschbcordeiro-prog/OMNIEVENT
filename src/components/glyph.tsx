/** The line icon for an emoji, if there is one. */
export function glyphFor(emoji?: string | null): LucideIcon | null {
  if (!emoji) return null;
  return MAP[emoji] ?? MAP[emoji.replace(/️/g, "")] ?? MAP[`${emoji}️`] ?? null;
}

/** A country's flag (two regional letters): kept as it is, it's the country's own mark. */
export const isFlag = (e?: string | null) => !!e && /^[\u{1F1E6}-\u{1F1FF}]{2}$/u.test(e);

/** Draws the line icon for an emoji (nothing when there's none, or `fallback`). Decorative: the words say it. */
export function Glyph({ e, size = 15, className = "", fallback }: { e?: string | null; size?: number; className?: string; fallback?: LucideIcon }) {
  const Icon = glyphFor(e) ?? fallback;
  if (!Icon) return null;
  return <Icon size={size} strokeWidth={1.9} className={`glyph ${className}`} aria-hidden />;
}

/** Takes the emoji out of a line of text written with them ("🎉 Free" → "Free"). */
export function plain(text: string): string {
  return text
    .replace(/[\p{Extended_Pictographic}\u{1F1E6}-\u{1F1FF}️‍]/gu, "")
    .replace(/\s{2,}/g, " ")
    .trim();
}
